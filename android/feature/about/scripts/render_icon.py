"""Render the approved Night drive launcher icon and splash icon into :feature:about's resources.

Sources (approved, frozen; never edited here): docs/design/app-icon/icon-background.svg,
icon-foreground.svg and icon-monochrome.svg. Renderer: resvg 0.49.0 (tools/bin/resvg, fetched by
tools/fetch_art_tools.py), which draws the foreground's Gaussian blurs; Android's vector drawables
cannot, so the foreground ships as bitmaps (docs/architecture.md 5.1, A).

Writes, under android/feature/about/src/main/res/:
  mipmap-<density>/ic_launcher_background.png   108 dp (adaptive icon canvas), every density
  mipmap-<density>/ic_launcher_foreground.png   108 dp
  drawable-<density>/splash_icon_background.png 288 dp (the system splash icon and the reveal)
  drawable-<density>/splash_icon_foreground.png 288 dp
  drawable/ic_launcher_monochrome.xml           vector, from icon-monochrome.svg (themed icons)

Usage, from the repository root:
  python android/feature/about/scripts/render_icon.py           render and write
  python android/feature/about/scripts/render_icon.py --check   render into a temporary folder
                                                                and compare; exit 1 on a difference
Standard library only (the renderer is the resvg executable).
"""
from __future__ import annotations

import argparse
import hashlib
import os
import re
import shutil
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

REPO = Path(__file__).resolve().parents[4]
MODULE = REPO / "android" / "feature" / "about"
RES = MODULE / "src" / "main" / "res"
DESIGN = REPO / "docs" / "design" / "app-icon"
RESVG = REPO / "tools" / "bin" / "resvg" / ("resvg.exe" if os.name == "nt" else "resvg")

# Android density buckets: px per dp.
DENSITIES = {"mdpi": 1.0, "hdpi": 1.5, "xhdpi": 2.0, "xxhdpi": 3.0, "xxxhdpi": 4.0}
LAUNCHER_DP = 108   # adaptive icon layer: 108 x 108 dp, the middle 72 dp visible
SPLASH_DP = 288     # splash icon without an icon background: 288 dp, a 192 dp circle visible

# (resource folder prefix, file name, source SVG, size in dp)
BITMAPS = [
    ("mipmap", "ic_launcher_background.png", "icon-background.svg", LAUNCHER_DP),
    ("mipmap", "ic_launcher_foreground.png", "icon-foreground.svg", LAUNCHER_DP),
    ("drawable", "splash_icon_background.png", "icon-background.svg", SPLASH_DP),
    ("drawable", "splash_icon_foreground.png", "icon-foreground.svg", SPLASH_DP),
]

MONOCHROME_XML = "drawable/ic_launcher_monochrome.xml"


def render(svg: Path, px: int, out: Path) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    cmd = [str(RESVG), "-w", str(px), "-h", str(px), str(svg), str(out)]
    subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL)


def monochrome_vector() -> str:
    """The themed-icon layer as an Android vector drawable, made from icon-monochrome.svg."""
    src = (DESIGN / "icon-monochrome.svg").read_text(encoding="utf-8")
    root = ET.fromstring(src)
    ns = {"s": "http://www.w3.org/2000/svg"}
    if root.get("viewBox") != "0 0 108 108":
        raise SystemExit("icon-monochrome.svg: expected viewBox 0 0 108 108")
    group = root.find("s:g", ns)
    path = group.find("s:path", ns) if group is not None else None
    if group is None or path is None:
        raise SystemExit("icon-monochrome.svg: expected one <g> holding one <path>")
    m = re.fullmatch(r"translate\(([-\d.]+) ([-\d.]+)\) scale\(([-\d.]+)\)", group.get("transform", ""))
    if not m:
        raise SystemExit("icon-monochrome.svg: expected transform translate(x y) scale(s)")
    tx, ty, s = m.groups()
    scale = s if not s.startswith(".") else "0" + s
    d = path.get("d")
    # Vector drawable group order: scale (about pivot 0,0), then translate: the same as SVG's
    # "translate(...) scale(...)". The fill colour is ignored by the launcher (it tints the layer).
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Night drive themed-icon layer (Android 13+ monochrome). Generated by\n"
        "     android/feature/about/scripts/render_icon.py from docs/design/app-icon/icon-monochrome.svg;\n"
        "     do not edit by hand. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp"\n'
        '    android:height="108dp"\n'
        '    android:viewportWidth="108"\n'
        '    android:viewportHeight="108">\n'
        f'    <group\n'
        f'        android:translateX="{tx}"\n'
        f'        android:translateY="{ty}"\n'
        f'        android:scaleX="{scale}"\n'
        f'        android:scaleY="{scale}">\n'
        f'        <path\n'
        f'            android:fillColor="#FF000000"\n'
        f'            android:pathData="{d}" />\n'
        f'    </group>\n'
        "</vector>\n"
    )


def outputs() -> list[tuple[str, int, str, str]]:
    """(relative path under res/, px, source svg name, kind) for every bitmap."""
    items = []
    for prefix, name, svg, dp in BITMAPS:
        for dens, scale in DENSITIES.items():
            px = round(dp * scale)
            items.append((f"{prefix}-{dens}/{name}", px, svg, "png"))
    return items


def build(into: Path) -> None:
    for rel, px, svg, _ in outputs():
        render(DESIGN / svg, px, into / rel)
    mono = into / MONOCHROME_XML
    mono.parent.mkdir(parents=True, exist_ok=True)
    mono.write_bytes(monochrome_vector().encode("utf-8"))


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="compare the resources with a fresh render")
    args = ap.parse_args()
    if not RESVG.exists():
        print(f"render_icon.py: {RESVG.relative_to(REPO)} is missing; run python tools/fetch_art_tools.py", file=sys.stderr)
        return 2
    rels = [o[0] for o in outputs()] + [MONOCHROME_XML]
    if args.check:
        with tempfile.TemporaryDirectory() as tmp:
            build(Path(tmp))
            bad = []
            for rel in rels:
                have = RES / rel
                if not have.exists() or sha(have) != sha(Path(tmp) / rel):
                    bad.append(rel)
        for rel in bad:
            print(f"differs  res/{rel}")
        print(f"{len(rels)} files checked; " + ("all the same" if not bad else f"{len(bad)} differ"))
        return 1 if bad else 0
    build(RES)
    for rel, px, svg, _ in outputs():
        print(f"wrote    res/{rel}  {px} x {px} px  from {svg}")
    print(f"wrote    res/{MONOCHROME_XML}  from icon-monochrome.svg")
    return 0


if __name__ == "__main__":
    sys.exit(main())
