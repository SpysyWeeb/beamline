"""Generate categories_idterms.json (extra category words) from the iD tagging schema.

    python packbuilder/search/seed_categories.py            # download (pinned) + write
    python packbuilder/search/seed_categories.py --check    # only report, do not write

Downloads @openstreetmap/id-tagging-schema (version and SHA-256 pinned in
categories.json -> id_schema) into data/search/ref/idts/ once, then for every
category copies the preset name, aliases and terms of each preset listed in
id_presets, minus the global and per-category exclude lists. Words that are
also in the category's own terms are kept, so the file records every word that
came from iD. The result goes to a separate generated
file so hand-written and copied words never mix. Licence of the copied terms:
ISC (see the attribution field in categories.json).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
CATS = os.path.join(HERE, "categories.json")
OUT = os.path.join(HERE, "categories_idterms.json")
REF_DIR = os.path.join(REPO, "data", "search", "ref", "idts")


def fetch(pkg: str, version: str, path: str, sha256: str) -> str:
    os.makedirs(REF_DIR, exist_ok=True)
    dest = os.path.join(REF_DIR, os.path.basename(path))
    if not os.path.exists(dest):
        url = f"https://cdn.jsdelivr.net/npm/{pkg}@{version}/{path}"
        print("downloading", url)
        with urllib.request.urlopen(url, timeout=120) as r, open(dest + ".part", "wb") as f:
            f.write(r.read())
        os.replace(dest + ".part", dest)
    h = hashlib.sha256(open(dest, "rb").read()).hexdigest()
    if h != sha256:
        sys.exit(f"SHA-256 mismatch for {dest}: {h} != {sha256}")
    return dest


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="report only")
    args = ap.parse_args()
    with open(CATS, encoding="utf-8") as f:
        doc = json.load(f)
    s = doc["id_schema"]
    en_path = fetch(s["package"], s["version"], s["file"], s["sha256"])
    with open(en_path, encoding="utf-8") as f:
        presets = json.load(f)["en"]["presets"]["presets"]
    gex = {t.lower() for t in doc["id_terms_exclude_global"]}
    total = 0
    out: dict[str, list[str]] = {}
    for c in doc["categories"]:
        own = {(t[0] if isinstance(t, list) else t).lower() for t in c.get("terms", [])}
        cex = {t.lower() for t in c.get("id_terms_exclude", [])}
        got: list[str] = []
        for pid in c.get("id_presets", []):
            p = presets.get(pid)
            if p is None:
                print(f"  {c['id']}: preset {pid} not found in iD schema")
                continue
            words = [p.get("name", "")] + list(p.get("aliases", [])) + list(p.get("terms", []))
            for w in words:
                w = w.strip().lower()
                if w and w not in gex and w not in cex and w not in got:
                    got.append(w)
        out[c["id"]] = got
        total += len(got)
        print(f"{c['id']:20s} {len(c.get('terms', [])):3d} own, {len(got):2d} from iD: {', '.join(got)}")
    print(f"{len(doc['categories'])} categories, {total} terms copied from iD")
    if not args.check:
        result = {
            "_doc": "GENERATED by seed_categories.py - do not edit. Extra category terms copied from the iD tagging schema (preset name, aliases, terms) for the presets listed in categories.json -> id_presets, minus the exclude lists (words also in the category's own terms are kept, to record their source).",
            "attribution": doc["attribution"],
            "attribution_license": doc["attribution_license"],
            "source": s,
            "id_terms": out,
        }
        lines = ["{"]
        for k in ("_doc", "attribution", "attribution_license", "source"):
            lines.append(f"  {json.dumps(k)}: {json.dumps(result[k], ensure_ascii=False)},")
        lines.append('  "id_terms": {')
        items = list(out.items())
        for i, (cid, terms) in enumerate(items):
            comma = "," if i < len(items) - 1 else ""
            lines.append(f"    {json.dumps(cid)}: {json.dumps(terms, ensure_ascii=False)}{comma}")
        lines.append("  }")
        lines.append("}")
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines) + "\n")
        print("wrote", os.path.relpath(OUT, REPO))


if __name__ == "__main__":
    main()
